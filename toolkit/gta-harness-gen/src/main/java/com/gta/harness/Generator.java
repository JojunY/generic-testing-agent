package com.gta.harness;

import com.gta.core.util.Json;
import com.gta.core.util.Yaml;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

/**
 * Renders one platform folder (copilot/ or opencode/) from core/ and platforms/&lt;p&gt;/mapping.yaml (plan §11.4).
 * The result is a sorted map of relative path → content, so generation is deterministic and --check is a plain diff.
 */
public class Generator {
    static final String GENERATED = "<!-- generated by gta-harness-gen from %s; edit the source, not this file -->\n";

    private final Path repo;

    public Generator(Path repo) {
        this.repo = repo;
    }

    @SuppressWarnings("unchecked")
    public Map<String, String> render(String platform) {
        Map<String, Object> mapping = yaml(repo.resolve("platforms/" + platform + "/mapping.yaml"));
        Map<String, Object> agentCfg = (Map<String, Object>) mapping.get("agent");
        Map<String, Object> models = (Map<String, Object>) mapping.getOrDefault("models", Map.of());
        Map<String, Object> profiles = (Map<String, Object>) mapping.get("profiles");
        Map<String, String> out = new TreeMap<>();

        for (Path agentFile : list(repo.resolve("core/agents"), ".md")) {
            Frontmatter src = Frontmatter.parse(read(agentFile));
            Map<String, Object> f = src.fields();
            String name = (String) f.get("name");
            String profile = (String) f.get("permissionProfile");
            Map<String, Object> fm = new LinkedHashMap<>();
            if (Boolean.TRUE.equals(agentCfg.get("emitName"))) {
                fm.put("name", name);
            }
            fm.put("description", f.get("description"));
            Map<String, Object> profileFields = (Map<String, Object>) profiles.get(profile);
            if (profileFields == null) {
                throw new IllegalStateException(platform + " mapping has no profile " + profile + " (agent " + name + ")");
            }
            Object model = models.get(f.get("modelTier"));
            if (model != null) {
                fm.put("model", model);
            }
            fm.putAll(deepCopy(profileFields));
            boolean invocable = Boolean.TRUE.equals(f.get("userInvocable"));
            Object invocableField = agentCfg.get("invocableField");
            if (invocableField != null) {
                fm.put((String) invocableField, invocable);
            }
            if (!invocable) {
                fm.putAll((Map<String, Object>) agentCfg.getOrDefault("notInvocableFields", Map.of()));
            }
            Object subField = agentCfg.get("subagentsField");
            if (subField != null && f.get("subagents") instanceof List<?> subs && !subs.isEmpty()) {
                fm.put((String) subField, subs);
            }
            String file = ((String) agentCfg.get("file")).replace("{name}", name);
            String body = String.format(GENERATED, rel(agentFile)) + src.body();
            out.put(agentCfg.get("dir") + "/" + file, new Frontmatter(fm, body).render());
        }

        // the single command (/gta)
        Map<String, Object> cmd = (Map<String, Object>) mapping.get("command");
        Path cmdSrc = repo.resolve("core/commands/gta.md");
        Frontmatter c = Frontmatter.parse(read(cmdSrc));
        String cmdTemplate = read(platformFile(platform, (String) cmd.get("template")));
        String cmdBody = String.format(GENERATED, rel(cmdSrc)) + "\n" + c.body().strip().replace("{{args}}", (String) cmd.get("args")) + "\n";
        out.put((String) cmd.get("path"), cmdTemplate
                .replace("{{name}}", Frontmatter.scalar(c.fields().get("name")))
                .replace("{{description}}", Frontmatter.scalar(c.fields().get("description")))
                .replace("{{agent}}", Frontmatter.scalar(c.fields().get("agent")))
                .replace("{{body}}", cmdBody.stripTrailing()) .stripTrailing() + "\n");

        // merged config files
        for (Map<String, Object> file : (List<Map<String, Object>>) mapping.getOrDefault("files", List.of())) {
            String content = read(platformFile(platform, (String) file.get("template")));
            try {
                Json.MAPPER.readTree(content); // templates must be valid JSON; installer deep-merges them
            } catch (IOException e) {
                throw new IllegalStateException("Template " + file.get("template") + " is not valid JSON: " + e.getMessage());
            }
            out.put((String) file.get("path"), content);
        }

        // AGENTS.md block, skills
        out.put("AGENTS.gta.md", read(repo.resolve("core/rules/gta-guardrails.md")));
        Path skills = repo.resolve("core/skills");
        try (Stream<Path> walk = Files.walk(skills)) {
            walk.filter(Files::isRegularFile).sorted().forEach(p ->
                    out.put(".gta/skills/" + skills.relativize(p).toString().replace('\\', '/'), read(p)));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }

        StringBuilder manifest = new StringBuilder("# Files installed by `gtaw init --platform " + platform + "` (generated)\n");
        out.keySet().forEach(k -> manifest.append(k).append('\n'));
        out.put("gta-manifest.txt", manifest.toString());
        return out;
    }

    /** Writes the rendered folder, removing files that are no longer generated. */
    public void write(String platform, Path target, Map<String, String> files) {
        try {
            if (Files.exists(target)) {
                try (Stream<Path> walk = Files.walk(target)) {
                    for (Path p : walk.sorted((a, b) -> b.getNameCount() - a.getNameCount()).toList()) {
                        String r = target.relativize(p).toString().replace('\\', '/');
                        if (Files.isRegularFile(p) && !files.containsKey(r)) {
                            Files.delete(p);
                        } else if (Files.isDirectory(p) && !p.equals(target) && isEmpty(p)) {
                            Files.delete(p);
                        }
                    }
                }
            }
            for (Map.Entry<String, String> e : files.entrySet()) {
                Path p = target.resolve(e.getKey());
                Files.createDirectories(p.getParent());
                Files.writeString(p, e.getValue(), StandardCharsets.UTF_8);
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Differences between the committed folder and a fresh render; empty when in sync. */
    public List<String> diff(Path target, Map<String, String> files) {
        List<String> problems = new ArrayList<>();
        for (Map.Entry<String, String> e : files.entrySet()) {
            Path p = target.resolve(e.getKey());
            if (!Files.exists(p)) {
                problems.add("missing " + rel(p));
            } else if (!read(p).equals(e.getValue())) {
                problems.add("stale   " + rel(p));
            }
        }
        if (Files.exists(target)) {
            try (Stream<Path> walk = Files.walk(target)) {
                walk.filter(Files::isRegularFile).forEach(p -> {
                    if (!files.containsKey(target.relativize(p).toString().replace('\\', '/'))) {
                        problems.add("extra   " + rel(p));
                    }
                });
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
        return problems;
    }

    private static boolean isEmpty(Path dir) throws IOException {
        try (Stream<Path> s = Files.list(dir)) {
            return s.findAny().isEmpty();
        }
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> deepCopy(Map<String, Object> m) {
        Map<String, Object> copy = new LinkedHashMap<>();
        m.forEach((k, v) -> copy.put(k, v instanceof Map<?, ?> mm ? deepCopy((Map<String, Object>) mm) : v));
        return copy;
    }

    private Path platformFile(String platform, String name) {
        return repo.resolve("platforms/" + platform + "/" + name);
    }

    String rel(Path p) {
        return repo.relativize(p).toString().replace('\\', '/');
    }

    static List<Path> list(Path dir, String suffix) {
        try (Stream<Path> s = Files.list(dir)) {
            return s.filter(p -> p.getFileName().toString().endsWith(suffix)).sorted().toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    @SuppressWarnings("unchecked")
    static Map<String, Object> yaml(Path p) {
        try {
            return Yaml.MAPPER.readValue(p.toFile(), LinkedHashMap.class);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + p + ": " + e.getMessage(), e);
        }
    }

    static String read(Path p) {
        try {
            return Files.readString(p, StandardCharsets.UTF_8).replace("\r\n", "\n");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
