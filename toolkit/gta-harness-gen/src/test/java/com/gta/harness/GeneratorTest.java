package com.gta.harness;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** copilot/ and opencode/ are rendered from core/ + platforms/ (AGENTS.md: never edit them by hand). */
class GeneratorTest {
    static final Path REPO = Path.of("../..").toAbsolutePath().normalize();

    @Test
    void shouldWriteAFolderThatMatchesTheRenderAndSaysItIsGenerated(@TempDir Path out) throws Exception {
        Generator gen = new Generator(REPO);
        Map<String, String> files = gen.render("copilot");
        Path target = out.resolve("copilot");

        gen.write("copilot", target, files);

        assertEquals(List.of(), gen.diff(target, files));
        assertTrue(Files.readString(target.resolve("README.md")).startsWith("# copilot/ (generated)"));
        assertTrue(files.get(".github/agents/gta-reviewer.agent.md")
                .contains("<!-- generated by gta-harness-gen from core/agents/gta-reviewer.md"));
        assertTrue(files.containsKey("gta-manifest.txt"));
        assertTrue(!files.containsKey("README.md"), "the README is not installed into services");
    }

    @Test
    void shouldReportStaleExtraAndMissingFilesAndRemoveObsoleteOnes(@TempDir Path out) throws Exception {
        Generator gen = new Generator(REPO);
        Map<String, String> files = gen.render("opencode");
        Path target = out.resolve("opencode");
        gen.write("opencode", target, files);
        String someFile = files.keySet().stream()
                .filter(k -> k.endsWith(".md"))
                .findFirst()
                .orElseThrow();
        Files.writeString(target.resolve(someFile), "edited by hand");
        Files.writeString(target.resolve("stray.txt"), "x");
        Files.delete(target.resolve("gta-manifest.txt"));

        List<String> diff = gen.diff(target, files);

        assertTrue(diff.stream().anyMatch(d -> d.startsWith("stale") && d.contains(someFile)), diff.toString());
        assertTrue(diff.stream().anyMatch(d -> d.startsWith("extra") && d.contains("stray.txt")), diff.toString());
        assertTrue(
                diff.stream().anyMatch(d -> d.startsWith("missing") && d.contains("gta-manifest.txt")),
                diff.toString());

        gen.write("opencode", target, files);
        assertEquals(List.of(), gen.diff(target, files), "writing again removes the stray file");
    }
}
